import { TrailIntentParser } from "./parser/intentParser.js";
import { TrailheadTemporalManager } from "./temporal/client.js";

async function runSimulation() {
  console.log(`\n========================================================================`);
  console.log(`🌲 TRAILHEAD PROMISE: AUTONOMOUS END-TO-END FIELD SIMULATION`);
  console.log(`========================================================================\n`);

  // 1. Spoken audio transcript recorded by hiker at trailhead
  const sampleVoiceNote = `Hey, heading up to Hundru Falls gorge perimeter via East Gate.
Expected duration is roughly 3 hours, should be back by 6:00 PM.
If I don't check in, alert my brother Rahul at 9876543210.
Watch out for flash floods near the lower crossing.`;

  console.log(`[STEP 1] 🎙️ Ingesting Hiker Audio Transcript:`);
  console.log(`"${sampleVoiceNote}"\n`);

  // 2. Parse into structured schema
  const plan = await TrailIntentParser.parseTranscript(sampleVoiceNote, { lat: 23.4475, lng: 85.6543 });
  console.log(`[STEP 2] 🧠 Structured Schema Generated by Gemma & Validated by Zod:`);
  console.dir(plan, { depth: null });

  // 3. Commit to Temporal Durable Workflow
  const planId = `SIM-${Date.now().toString(36).toUpperCase()}`;
  const workflowSession = await TrailheadTemporalManager.startHikeSafetyWorkflow(planId, plan);
  console.log(`\n[STEP 3] ⚡ Temporal Durable Workflow Started: ID = ${workflowSession.workflowId} (Mode: ${workflowSession.mode})`);

  // 4. Query Initial State
  let state = await TrailheadTemporalManager.getWorkflowState(planId);
  console.log(`\n[STEP 4] 📡 Initial Workflow State: Status = ${state.status}, Remaining = ${state.remainingMinutes} min`);

  // 5. Simulate Field Event: Critical Low Battery (< 5%)
  console.log(`\n[STEP 5] 🪫 Simulating Field Telemetry: Battery drops to 4% at remote GPS waypoint...`);
  state = await TrailheadTemporalManager.signalLowBattery(planId, {
    latitude: 23.4512,
    longitude: 85.6610,
    batteryPercent: 4,
  });
  console.log(`Updated State: Status = ${state.status}, Battery = ${state.batteryPercent}%`);

  // 6. Simulate Safe Check-In
  console.log(`\n[STEP 6] ✅ Simulating Hiker Reaching Trailhead: Firing Safe Check-In Signal...`);
  state = await TrailheadTemporalManager.signalCheckIn(planId);
  console.log(`Final Workflow State: Status = ${state.status}`);
  console.log(`Timeline History:`);
  state.eventLog.forEach((log) => {
    console.log(`  • [${log.type}] ${log.message}`);
  });

  console.log(`\n========================================================================`);
  console.log(`🏆 SIMULATION VERIFIED: Indestructible Backcountry Safety Achieved!`);
  console.log(`========================================================================\n`);
}

runSimulation().catch(console.error);
